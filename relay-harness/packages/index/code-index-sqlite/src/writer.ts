/**
 * Incremental file-delta writer over the derived SQLite store.
 *
 * Ported from the reference implementation's file-batch writers
 * (`cc-db/src/index_db_write_batch.rs`). Every delta commits as exactly one
 * {@link ./epoch.ts!bumpIndexEpochOnceInTx | epoch-bumped} transaction:
 * per-path FTS-mirror deletes resolve doomed rowids through the still-present
 * base rows and run BEFORE the base deletes, chunk insertion mirrors plain
 * text into `chunks_fts` under the base row's own rowid, optional per-file
 * graph rows (`symbols` / `imports` / `symbol_refs` / `call_edges` /
 * `test_edges` / `literal_index`) ride the same delete-then-insert cycle, and
 * the whole unit rolls back atomically on any failure.
 *
 * @module @relay-harness/rlh-code-index-sqlite/writer
 */

